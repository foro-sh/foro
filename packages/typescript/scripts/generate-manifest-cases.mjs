// Inlines packages/python/src/foro/manifest-cases.json as a TypeScript module
// so foro-sh/platform can import the same table.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(here, '..', '..', 'python', 'src', 'foro', 'manifest-cases.json')
const TARGET = join(here, '..', 'src', '_generated-manifest-cases.ts')

const cases = JSON.parse(readFileSync(SOURCE, 'utf8'))

if (!Array.isArray(cases) || cases.length === 0) {
  throw new Error(`${SOURCE}: expected a non-empty array of cases`)
}

const seen = new Set()
for (const testCase of cases) {
  const { name, files, expect } = testCase ?? {}
  if (typeof name !== 'string' || typeof files !== 'object' || files === null) {
    throw new Error(`${SOURCE}: every case needs a string \`name\` and a \`files\` map`)
  }
  if (!Object.values(files).every((contents) => typeof contents === 'string')) {
    throw new Error(`${SOURCE}: case "${name}" has a non-string file`)
  }
  if (seen.has(name)) {
    throw new Error(`${SOURCE}: duplicate case name "${name}"`)
  }
  seen.add(name)

  if (expect?.ok === true) continue
  if (expect?.ok === false && typeof expect.reason === 'string') continue
  throw new Error(
    `${SOURCE}: case "${name}" must expect either {ok: true} or {ok: false, reason: "..."}`,
  )
}

const banner = [
  '// Generated by scripts/generate-manifest-cases.mjs from the Python package\'s',
  '// manifest-cases.json. Do not edit - edit the JSON and rebuild.',
  '',
].join('\n')

// `as const` so a new reason fails the ManifestRejectionReason assignment.
writeFileSync(
  TARGET,
  `${banner}export const rawManifestCases = ${JSON.stringify(cases, null, 2)} as const\n`,
)

console.log(`generated ${TARGET} (${cases.length} cases)`)
